#!/usr/bin/env python3
"""Generate src/assets.cpp and optional CDN manifest from models/."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

NAMES = [
    "caption_config.json",
    "caption_decoder.onnx",
    "caption_encoder.onnx",
    "caption_tokenizer.json",
    "imagenet_labels.txt",
    "mobilenet_tags.onnx",
    "ppocr_cls.onnx",
    "ppocr_det.onnx",
    "ppocr_keys.txt",
    "ppocr_rec.onnx",
    "scrfd_det.onnx",
    "w600k_mbf.onnx",
    "yolo26n.onnx",
]


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_manifest(models: Path, manifest: Path) -> None:
    files = []
    for name in NAMES:
        path = models / name
        if not path.is_file():
            raise SystemExit(f"missing model for manifest: {path}")
        files.append({"name": name, "sha256": sha256_file(path), "size": path.stat().st_size})
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(
        json.dumps({"module": "eyes", "version": "2.0.0", "files": files}, indent=2) + "\n"
    )
    print(f"[+] wrote {manifest} ({len(files)} files)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("models", type=Path, help="directory containing model files")
    parser.add_argument("out_cpp", type=Path, help="path for generated assets.cpp")
    parser.add_argument("--manifest", type=Path, help="optional CDN manifest.json path")
    args = parser.parse_args()
    models = args.models
    out = args.out_cpp
    rows: list[tuple[str, str]] = []
    for name in NAMES:
        path = models / name
        if not path.is_file():
            raise SystemExit(f"missing model: {path}")
        rows.append((sha256_file(path), name))
    lines = [
        "// Code generated by scripts/gen_assets.py; DO NOT EDIT.",
        '#include "assets.h"',
        "",
        "namespace eyes::assets {",
        "",
        "namespace {",
        "",
        "struct Entry {",
        "  const char* sha256;",
        "  const char* name;",
        "};",
        "",
        "static const Entry kEntries[] = {",
    ]
    for digest, name in rows:
        lines.append(f'  {{"{digest}", "{name}"}},')
    lines += [
        "};",
        "",
        "}  // namespace",
        "",
        f"int count() {{ return static_cast<int>(sizeof(kEntries) / sizeof(kEntries[0])); }}",
        "",
        "std::string describe(int index) {",
        "  if (index < 0 || index >= count()) return \"\";",
        "  const Entry& e = kEntries[index];",
        "  return std::string(e.sha256) + \",\" + e.name;",
        "}",
        "",
        "}  // namespace eyes::assets",
        "",
    ]
    out.write_text("\n".join(lines))
    print(f"[+] wrote {out} ({len(rows)} assets)")
    if args.manifest:
        write_manifest(models, args.manifest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
